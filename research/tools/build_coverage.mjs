// Renders research/theory_coverage.md from research/theories.json and the ledger.
//   node research/tools/build_coverage.mjs          write the file
//   node research/tools/build_coverage.mjs --check  exit 1 if the file is out of date
// test/theories.test.js runs render() and compares, so the table cannot drift from the registry.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../../', import.meta.url);
const read = (p) => readFileSync(new URL(p, ROOT), 'utf8');
const OUT = 'research/theory_coverage.md';

const cell = (s) => (s == null || s === '' ? '—' : String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '));
const STATUS = { established: 'ESTABLISHED', derived: 'DERIVED CONNECTION', hypothesis: 'HYPOTHESIS', open: 'OPEN QUESTION', governance: 'METHOD RULE' };
const BEFORE = { preserved: 'preserved', partial: 'partial', 'title-only': 'title only', missing: 'MISSING', new: 'new' };

export function render() {
  const { theories } = JSON.parse(read('research/theories.json'));
  const ledger = JSON.parse(read('verify/ledger/latest.json')).cards;
  const ev = (list) =>
    list.length === 0
      ? '—'
      : list
          .map((e) => {
            const [kind, id] = e.ref.split(/:(.*)/s);
            const tag = kind === 'card' ? `${id} (${ledger[id]?.verdict ?? 'not on ledger'})` : kind === 'uncarded' ? 'no card yet' : `${kind}: ${id}`;
            return e.note ? `${tag}: ${e.note}` : tag;
          })
          .join('; ');
  const against = (r) => [ev(r.evidenceAgainst), ...r.boundaries.map((b) => `boundary: ${b}`)].filter((x) => x !== '—').join('; ') || '—';
  const words = (r) => [r.words, ...r.variants.map((v) => `${v.words} *(${v.source})*`)].filter(Boolean).map((w) => `“${w}”`).join(' / ');
  const rel = (r) => [r.supersededBy && `superseded by ${r.supersededBy}`, r.supersedes && `supersedes ${r.supersedes}`].filter(Boolean).join('; ');
  const row = (r) =>
    `| ${r.id} | ${cell(words(r))} | ${cell([r.normalizedStatement, rel(r)].filter(Boolean).join(' · '))} | ${r.origin} | ${STATUS[r.status]} | ${cell(r.sourceDocs[0])} | ${cell(r.graphRecord)} | ${cell(r.relatedActs.join(', ') + (r.relatedActsRev3.length ? ` (rev 3: ${r.relatedActsRev3.join(', ')})` : ''))} | ${cell(r.interactive)} | ${cell(ev(r.evidenceFor))} | ${cell(against(r))} | ${BEFORE[r.audit.before]}${r.audit.note ? `: ${cell(r.audit.note)}` : ''} |`;

  const user = theories.filter((r) => r.origin === 'user');
  const other = theories.filter((r) => r.origin !== 'user');
  const passCards = (r) => r.evidenceFor.filter((e) => e.ref.startsWith('card:') && ledger[e.ref.slice(5)]?.verdict === 'PASS');
  const ids = (list) => (list.length ? list.map((r) => r.id).join(', ') : '—');
  const by = (k) => user.filter((r) => r.audit.before === k);
  const head = '| ID | Original wording | Normalized wording | Origin | Status | Source document | Graph record | Act (new map; rev 3) | Interactive coverage | Evidence for | Evidence against / boundary | Before this audit |\n|---|---|---|---|---|---|---|---|---|---|---|---|';

  return `# Theory coverage

Generated by \`research/tools/build_coverage.mjs\` from \`research/theories.json\` and the ledger. Do not edit by hand.

One row per user-origin theory or question. Original wording is quoted exactly from the source document; the
registry test checks every quote. Evidence against a theory is attached to it and never removes it.
Superseded wordings keep their own rows. "Before this audit" records what the repository held before the theory
registry existed.

Master Map and Mathematical Basis spec wording is assistant-written, addressed to Nadia: where a row's source is
\`docs/Interactive_Master_Map.extracted.md\` or the spec, the idea is attributed to Nadia in that document's words, not quoted from her.

## Summary (user-origin records: ${user.length})

| Before this audit | Count | Records |
|---|---|---|
${['preserved', 'partial', 'title-only', 'missing', 'new'].map((k) => `| ${BEFORE[k]} | ${by(k).length} | ${ids(by(k))} |`).join('\n')}

| Now | Count | Records |
|---|---|---|
| cites a PASS card (for a HYPOTHESIS or OPEN QUESTION the card supports an ingredient, not the theory) | ${user.filter((r) => passCards(r).length).length} | ${ids(user.filter((r) => passCards(r).length))} |
| has counterevidence, a FAIL kept, or a boundary | ${user.filter((r) => r.evidenceAgainst.length || r.boundaries.length).length} | ${ids(user.filter((r) => r.evidenceAgainst.length || r.boundaries.length))} |
| completely open (no evidence for or against; scope notes allowed) | ${user.filter((r) => !r.evidenceFor.length && !r.evidenceAgainst.length).length} | ${ids(user.filter((r) => !r.evidenceFor.length && !r.evidenceAgainst.length))} |
| superseded wording kept as history | ${user.filter((r) => r.supersededBy).length} | ${ids(user.filter((r) => r.supersededBy))} |

## Ratings (docs/research_method.md §12)

Backbone Support % and AI Slop / Delusion Risk % for every assessed result. Low support means continue carefully,
not discard. The transfer tests are in \`research/application_matrix.md\`.

| ID | Status | Correctness | Backbone Support | AI Slop Risk | Transfer Depth | Application Breadth (0–5) | Classification | Breadth | Branch |
|---|---|---|---|---|---|---|---|---|---|
${theories.filter((r) => r.assessment).map((r) => { const a = r.assessment; const h = a.ratingHistory.map((x) => ` (was ${x.fromBackbone}%/${x.fromSlop}%)`).join(''); return `| ${r.id} | ${STATUS[r.status]} | ${a.mathematicalCorrectness} | ${a.backboneSupport}%${h} | ${a.slopRisk}% | ${a.transferDepth} | ${a.applicationBreadth} | ${a.classification} | ${a.breadth} | ${a.branchState} |`; }).join('\n')}

## Constructions

| Construction | Record | Cards |
|---|---|---|
| R4 orthogonal-source construction (tetrahedral zero construction) | \`research/constructions/r4_tetrahedral_zero.md\` | G2a–G2k, G2n, G3a–G3d, G3n |
| Zero as connector, linear case | \`research/constructions/zero_connector_linear.md\` | G4a–G4c, G4m |
| WMC — Weighted Mass Centering | \`research/constructions/weighted_mass_centering.md\` | G5a–G5c, G5e |
| T′ vs WMC comparison (C_G, locked to **1**) | \`research/constructions/centering_comparison.md\` | G5b–G5f |
| Quantum Additive Cancellation Pair | \`research/constructions/quantum_additive_cancellation.md\` (blind protocol: \`qacp_blind_protocol.md\`) | Q2a–Q2g, W3a–W3b |

## Backbone records

Nadia's backbone statements (outside-in clarification). Every record keeps her original words; full rows are below.

Method rules (status METHOD RULE) carry no epistemic status and need no proof; hypotheses are kept in separate records.

| ID | Statement (Nadia's words) | Kind | Status | Related |
|---|---|---|---|---|
${theories.filter((r) => r.id.startsWith('B-')).map((r) => `| ${r.id} | ${cell(r.words)} | ${r.kind} | ${STATUS[r.status]} | ${cell(r.related.join(', '))} |`).join('\n')}

## Construction programs (primary mode: outside-in)

Every record has \`researchDirection: outside-in\`: construct first, classify second (\`docs/research_method.md\`). These
records carry a construction program. Known examples are never assumed exhaustive unless a stated theorem says so.

| ID | Sequence | Questions | Do not reason | Known examples (exhaustive?) |
|---|---|---|---|---|
${theories.filter((r) => r.construction).map((r) => { const c = r.construction; return `| ${r.id} | ${cell(c.sequence.join(' / '))} | ${cell(c.questions.join(' / '))} | ${cell(c.doNotReason.join(' / '))} | ${cell(c.knownExamples.items.join(', '))}${c.knownExamples.items.length ? (c.knownExamples.exhaustive ? ` (exhaustive: ${cell(c.knownExamples.basis)})` : ' (known examples, not exhaustive)') : ''} |`; }).join('\n')}

## Proof programs (secondary mode)

Every record has \`researchMode: theorem-target\` whatever its status: the theory holds during construction. These
records carry a proof target; the rest acquire one when a construction yields a precise claim. "Last outcome" stays
empty until a research pass reports one. Earlier targets are kept as \`previousTargets\`.

| ID | Status | Target (Nadia's words) | Obligations listed | Earlier target | Last outcome |
|---|---|---|---|---|---|
${theories.filter((r) => r.proofTarget).map((r) => `| ${r.id} | ${STATUS[r.status]} | ${cell(r.proofTarget.targetStatement)} | ${r.proofTarget.proofObligations.length} | ${cell(r.proofTarget.previousTargets.map((p) => `${p.targetStatement} (${p.replacedBecause})`).join('; '))} | ${cell(r.proofTarget.lastResearchOutcome)} |`).join('\n')}

## User-origin theories and questions

${head}
${user.map(row).join('\n')}

## Assistant-proposed connections (adopted at Gate 3), for reference

${head}
${other.map(row).join('\n')}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    if (read(OUT) !== text) { console.error(`${OUT} is out of date: run node research/tools/build_coverage.mjs`); process.exit(1); }
  } else {
    writeFileSync(new URL(OUT, ROOT), text);
    console.log(`wrote ${OUT}`);
  }
}
