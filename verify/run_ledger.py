"""Run every verify/verify_*.py and append each card's verdict to the ledger.

The ledger is append-only (Gate 3): verify/ledger/ledger.jsonl only ever gains lines. A card that has
failed at any point stays marked in verify/ledger/summary.md even after a later, separately labelled
test passes. Failures that happened before this ledger existed (S14a, C8c, B5a) are still produced by
their scripts on every run, so they appear in every run's record.

Run:  python3 verify/run_ledger.py
"""

import datetime
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
LEDGER = HERE / "ledger" / "ledger.jsonl"
SUMMARY = HERE / "ledger" / "summary.md"
LINE = re.compile(r"^(\S+)\s+(PASS|FAIL)\s+(.*)$")


def commit():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, capture_output=True, text=True).stdout.strip()
    except OSError:
        return "unknown"


def run_script(path):
    out = subprocess.run([sys.executable, "-I", str(path)], cwd=HERE.parent, capture_output=True, text=True)
    cards, seen = [], {}
    for line in out.stdout.splitlines():
        m = LINE.match(line.strip())
        if not m:
            continue
        sid, verdict, claim = m.groups()
        seen[sid] = seen.get(sid, 0) + 1
        key = sid if seen[sid] == 1 else f"{sid}({seen[sid]})"
        cards.append({"id": key, "verdict": verdict, "claim": claim})
    if out.returncode != 0 and not cards:
        cards.append({"id": path.stem, "verdict": "ERROR", "claim": out.stderr.strip().splitlines()[-1] if out.stderr else "no output"})
    return cards


def main():
    stamp = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    sha = commit()
    rows = []
    for path in sorted(HERE.glob("verify_*.py")):
        for c in run_script(path):
            rows.append({"run": stamp, "commit": sha, "script": path.name, **c})

    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    with LEDGER.open("a", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    history = [json.loads(l) for l in LEDGER.read_text(encoding="utf-8").splitlines() if l.strip()]
    ever_failed = {(h["script"], h["id"]) for h in history if h["verdict"] != "PASS"}
    first_seen = {}
    for h in history:
        first_seen.setdefault((h["script"], h["id"]), h["run"])

    lines = [
        "# Verifier ledger: current state",
        "",
        f"Generated by `verify/run_ledger.py` at {stamp} (commit `{sha}`). The full history is in `ledger.jsonl`, which is append-only.",
        "",
        "| Script | Card | Now | Ever failed | First recorded | Claim |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        k = (r["script"], r["id"])
        flag = "yes" if k in ever_failed else ""
        lines.append(f"| `{r['script']}` | {r['id']} | **{r['verdict']}** | {flag} | {first_seen[k][:10]} | {r['claim'].replace('|', '/')} |")
    passed = sum(r["verdict"] == "PASS" for r in rows)
    lines += ["", f"**{passed}/{len(rows)} PASS this run.** FAILs are kept, not fixed in place."]
    SUMMARY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{passed}/{len(rows)} PASS · appended {len(rows)} rows → {LEDGER.relative_to(HERE.parent)}")
    for r in rows:
        if r["verdict"] != "PASS":
            print(f"  {r['verdict']}: {r['script']} {r['id']}  {r['claim'][:90]}")


if __name__ == "__main__":
    main()
